#!/usr/bin/env python3
"""The delivery and release log (decision 0145 §4, Phase 1).

    python3 tools/page-audit/deliveries.py record <build.zip> --mirror <checkout> [--note "what it does"]
    python3 tools/page-audit/deliveries.py verify --mirror <checkout>

record: writes deliveries/<zip name>.json with each file's SHA-256 and the sync it was built on, status "pending".
verify: for every pending delivery, compares each file with the live mirror. All match: "live", with the sync that
        brought it. Some match: "partial", listing the files still missing (a missed upload). Then rewrites
        deliveries/README.md, newest first.
"""
import argparse, datetime, glob, hashlib, json, os, sys, zipfile

MAP = {'website': 'sync-storage', 'app': 'sync-app', 'trvgo': 'sync-trvgo'}
HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.abspath(os.path.join(HERE, '..', '..'))
DIR = os.path.join(DOCS, 'deliveries')

def sync_of(mirror):
    return os.popen(f'git -C "{mirror}" log -1 --format="%h %s" 2>/dev/null').read().strip()

def record(a):
    os.makedirs(DIR, exist_ok=True)
    files = {}
    with zipfile.ZipFile(a.zip) as z:
        for n in z.namelist():
            if not n.endswith('/'):
                files[n] = hashlib.sha256(z.read(n)).hexdigest()
    name = os.path.splitext(os.path.basename(a.zip))[0]
    d = {'zip': os.path.basename(a.zip), 'built_on': sync_of(a.mirror), 'recorded': now(), 'note': a.note or '',
         'status': 'pending', 'live_in': '', 'files': {f: {'sha256': h, 'live': False} for f, h in sorted(files.items())}}
    json.dump(d, open(os.path.join(DIR, name + '.json'), 'w'), indent=1)
    write_readme()
    print(f'Recorded {name}: {len(files)} files, built on {d["built_on"]}')

def now():
    return datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')

def verify(a):
    s = sync_of(a.mirror)
    for p in sorted(glob.glob(os.path.join(DIR, '*.json'))):
        d = json.load(open(p))
        if d['status'] == 'live':
            continue
        for f, v in d['files'].items():
            top, _, rest = f.partition('/')
            live = os.path.join(a.mirror, MAP.get(top, top), rest)
            v['live'] = os.path.exists(live) and hashlib.sha256(open(live, 'rb').read()).hexdigest() == v['sha256']
        n = sum(v['live'] for v in d['files'].values())
        d['status'] = 'live' if n == len(d['files']) else ('partial' if n else 'pending')
        if d['status'] == 'live':
            d['live_in'] = s
        json.dump(d, open(p, 'w'), indent=1)
    write_readme()

def write_readme():
    rows = []
    for p in glob.glob(os.path.join(DIR, '*.json')):
        d = json.load(open(p))
        missing = [f for f, v in d['files'].items() if not v['live']]
        rows.append((d['recorded'], d, missing))
    L = ['# Deliveries', '', 'Decision 0145 §4. Every zip, what it was built on, and whether each file reached the live site byte for byte.',
         'Generated by `tools/page-audit/deliveries.py`; don\'t edit by hand. "Partial" means files still not uploaded.', '',
         '| Zip | Built on | Status | Live in | Not live yet | What |', '|---|---|---|---|---|---|']
    for _, d, missing in sorted(rows, key=lambda r: r[0], reverse=True):
        L.append(f'| `{d["zip"]}` | {d["built_on"]} | {d["status"]} | {d["live_in"]} | ' + ', '.join(f'`{m}`' for m in missing[:5])
                 + (' …' if len(missing) > 5 else '') + f' | {d.get("note", "")} |')
    open(os.path.join(DIR, 'README.md'), 'w').write('\n'.join(L) + '\n')

def main():
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest='cmd', required=True)
    r = sp.add_parser('record'); r.add_argument('zip'); r.add_argument('--mirror', required=True); r.add_argument('--note')
    v = sp.add_parser('verify'); v.add_argument('--mirror', required=True)
    a = ap.parse_args()
    record(a) if a.cmd == 'record' else verify(a)

if __name__ == '__main__':
    main()
