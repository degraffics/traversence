#!/usr/bin/env bash
# tools/page-audit/mail-dns.sh — the public DNS behind our notice emails (decisions/0137 §8): what mail providers check
# before trusting notices@send.traversence.com (SPF on the bounce domain, DKIM, DMARC, MX). Read only. Writes
# site-audit/mail-dns.md. Run by .github/workflows/search-probe.yml (Jason, 2026-11-10: the first notice went to Junk).
set -u
out=site-audit/mail-dns.md
q() { dig +short "$2" "$1" 2>/dev/null | tr '\n' ' ' | sed 's/ $//'; }
row() { local v; v=$(q "$1" "$2"); printf '| `%s` | %s | %s | %s |\n' "$1" "$2" "${v:-**missing**}" "$3"; }
{
  echo "# Mail DNS"
  echo
  echo "What mail providers check before trusting notices@send.traversence.com. Generated by \`tools/page-audit/mail-dns.sh\` on $(date -u '+%Y-%m-%d %H:%M') UTC. Don't edit by hand."
  echo
  echo "| Name | Type | Found | Needed |"
  echo "|---|---|---|---|"
  row send.traversence.com MX "not needed (mail is sent, not received, here)"
  row send.traversence.com TXT "nothing needed; SPF is on the bounce domain"
  row bounce.send.traversence.com MX "10 feedback-smtp.<region>.amazonses.com (SES custom MAIL FROM)"
  row bounce.send.traversence.com TXT "v=spf1 include:amazonses.com ~all"
  row _dmarc.send.traversence.com TXT "v=DMARC1; … (or inherited from _dmarc.traversence.com)"
  row _dmarc.traversence.com TXT "v=DMARC1; …"
  row traversence.com TXT "the main domain's own SPF (not used for send.)"
  echo
  echo "DKIM: SES signs with three CNAMEs named \`<token>._domainkey.send.traversence.com\` → \`<token>.dkim.amazonses.com\`. Their names are random; the site keeps them (System Configuration → Email). Without them, Outlook marks the mail Unverified."
} > "$out"
echo "wrote $out"
