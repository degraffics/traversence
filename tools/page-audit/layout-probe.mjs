// tools/page-audit/layout-probe.mjs — measures what a phone shows on a few pages (Jason, 2026-11-10: "The spacing at the top
// of the page and the green buttons over the action icons"): the gap between the top bar and the hero (it should be
// none, decisions/0058 §21) and anything drawn over the action icons on a place's card. Signed out, 390px, read only.
// Writes site-audit/layout-probe.md and screenshots to shots/ (kept with the run as an artifact, never committed).
// Run: SITE=https://traversence.com node tools/page-audit/layout-probe.mjs  (.github/workflows/search-probe.yml)
import { chromium } from 'playwright';
import { writeFileSync, mkdirSync } from 'node:fs';

const SITE = (process.env.SITE || 'https://traversence.com').replace(/\/$/, '');
const firstUrl = async (q, re) => {   // a real page of that kind, found through the site's own search
  try {
    const d = await (await fetch(`${SITE}/api/search.php?q=${encodeURIComponent(q)}`, { headers: { 'User-Agent': 'traversence-layout-probe' } })).json();
    const it = (d.results?.items || []).find((i) => re.test(i.url || ''));
    return it ? SITE + it.url : '';
  } catch { return ''; }
};

const pages = [
  ['A landmark', await firstUrl('glendale tract historic district', /\/place\/landmark\.php/)],
  ['A recreation place', await firstUrl('grand canyon', /\/place\/recreation\.php/)],
  ['Discovery', SITE + '/discovery/'],
  ['Parks & Landmarks', SITE + '/discovery/?view=parks'],
].filter(([, u]) => u);

mkdirSync('shots', { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, userAgent: 'Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Mobile Safari/537.36 traversence-layout-probe' });
let md = `# Layout probe\n\nWhat a phone (390px, signed out) shows, measured. Generated by \`tools/page-audit/layout-probe.mjs\` on ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC against ${SITE}. Don't edit by hand.\n\n`;
for (const [label, url] of pages) {
  const p = await ctx.newPage();
  try {
    await p.goto(url, { waitUntil: 'networkidle', timeout: 30000 });
    const m = await p.evaluate(() => {
      const r = (el) => (el ? el.getBoundingClientRect() : null);
      const hero = document.querySelector('.xh');
      // the bottom of what's fixed or sticky at the top (the account strip and the tool bar)
      let barBottom = 0;
      for (const el of document.querySelectorAll('header, nav, .tv-top, .tv-bar, [class*="topbar"], [class*="toolbar"]')) {
        const b = r(el); const cs = getComputedStyle(el);
        if (b && b.top < 200 && b.height > 20 && b.height < 220 && (cs.position === 'sticky' || cs.position === 'fixed' || b.top < 5)) barBottom = Math.max(barBottom, b.bottom);
      }
      const page = document.querySelector('.tv-page');
      const kids = page ? [...page.children].slice(0, 4).map((k) => `${k.tagName.toLowerCase()}${k.className && typeof k.className === 'string' ? '.' + k.className.trim().split(/\s+/).slice(0, 2).join('.') : ''}`) : [];
      const icons = document.querySelector('.lm-body > .lm-acts, .lm-acts[aria-label]');
      const ib = r(icons);
      const over = [];
      if (ib) {
        for (const el of document.querySelectorAll('.lm-info *')) {
          const b = r(el);
          if (!b || !b.width || !b.height || icons.contains(el)) continue;
          if (b.left < ib.right && b.right > ib.left && b.top < ib.bottom && b.bottom > ib.top && el.children.length === 0 && el.textContent.trim()) over.push(el.textContent.trim().slice(0, 30));
        }
      }
      // what stands between the bar and the hero: each container's top padding, margin and border, and its own top
      const chain = [];
      for (let el = hero; el && el !== document.body && chain.length < 8; el = el.parentElement) {
        const cs = getComputedStyle(el), b = r(el);
        chain.push(`${el.tagName.toLowerCase()}${typeof el.className === 'string' && el.className.trim() ? '.' + el.className.trim().split(/\s+/).slice(0, 2).join('.') : ''} top ${Math.round(b.top)} (pad ${cs.paddingTop}, margin ${cs.marginTop}, border ${cs.borderTopWidth})`);
      }
      const prev = hero && hero.previousElementSibling ? hero.previousElementSibling : null;
      return { chain, prev: prev ? `${prev.tagName.toLowerCase()} ${Math.round(r(prev).height)}px tall` : '', heroTop: hero ? Math.round(r(hero).top) : null, barBottom: Math.round(barBottom), firstKids: kids, over: [...new Set(over)].slice(0, 6),
               pageStyle: page ? getComputedStyle(page).paddingTop + ' padding, ' + (hero ? getComputedStyle(hero).marginTop + ' hero margin' : '') : '' };
    });
    const gap = m.heroTop !== null ? m.heroTop - m.barBottom : null;
    md += `## ${label}\n\n- **Page:** ${url.replace(SITE, '')}\n`;
    md += `- **Gap above the hero:** ${gap === null ? 'no hero' : gap + 'px'} (bar bottom ${m.barBottom}px, hero top ${m.heroTop}px; ${m.pageStyle})\n`;
    md += `- **First things on the page:** ${m.firstKids.join(', ') || '—'}\n`;
    if (m.chain && m.chain.length) md += `- **From the hero up:** ${m.chain.join(' › ')}${m.prev ? '; just before it: ' + m.prev : ''}\n`;
    if (m.over.length) md += `- **Drawn over the action icons:** ${m.over.join('; ')}\n`;
    md += '\n';
    await p.screenshot({ path: `shots/layout-${label.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}.png` }).catch(() => {});
  } catch (e) { md += `## ${label}\n\n- **Error:** ${String(e).slice(0, 160)}\n\n`; }
  await p.close();
}
// the search panel as someone types on a phone (Jason, 2026-11-11: "Location, results, location, results, maybe?"): the
// order it shows things in, top to bottom: the Location line, any question about where, then what the words mean, then
// where to go. Signed out, no place set.
md += `## The search panel while typing\n\n`;
for (const typed of ['jalapen', 'coffee near me']) {
  const p = await ctx.newPage();
  try {
    await p.goto(SITE + '/discovery/', { waitUntil: 'networkidle', timeout: 30000 });
    await p.click('#tv-search .tvs-in');
    await p.type('#tv-search .tvs-in', typed, { delay: 60 });
    await p.waitForTimeout(2500);
    const seen = await p.evaluate(() => {
      const panel = document.querySelector('.tvs-panel'); if (!panel) return ['(no panel)'];
      const out = [];
      for (const el of panel.querySelectorAll('.tvs-tsum, .tvs-loc, .tvs-locask .tvs-intent, h3.tvs-h, .tvs-t1 > *, .tvs-t1 .tvs-chipr button')) {
        const r = el.getBoundingClientRect(); if (!r.height || getComputedStyle(el).display === 'none') continue;
        const txt = (el.innerText || '').replace(/\s+/g, ' ').trim().slice(0, 70); if (txt) out.push(txt);
      }
      return [...new Set(out)].slice(0, 14);
    });
    md += `- **${typed}:** ${seen.map((x) => x.replace(/\|/g, '/')).join(' › ')}\n`;
    await p.screenshot({ path: `shots/panel-${typed.replace(/[^a-z0-9]+/gi, '-')}.png` }).catch(() => {});
  } catch (e) { md += `- **${typed}:** error ${String(e).slice(0, 120)}\n`; }
  await p.close();
}
md += '\n';
await browser.close();
writeFileSync('site-audit/layout-probe.md', md);
console.log(`${pages.length} pages measured`);
