// tools/page-audit/towns.mjs — towns built on demand (decisions/0147, 0149), from the health report: each town's crawl
// jobs (eat, stay, do, shops, care), what they found, published and left in Review, and any error. Totals only.
// Needs HEALTH_TOKEN (the GitHub secret). Writes site-audit/towns.md. Run by .github/workflows/search-probe.yml.
import { writeFileSync } from 'node:fs';
const SITE = process.env.SITE || 'https://traversence.com', TOKEN = process.env.HEALTH_TOKEN || '';
const s = (v) => (v == null ? '' : String(v)).replace(/\|/g, '/');
let md = `# Towns built on demand\n\nFrom the health report (\`/api/health.php\`), ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC. Generated by \`tools/page-audit/towns.mjs\`; don't edit by hand.\n\n`;
if (!TOKEN) md += 'HEALTH_TOKEN isn\'t set as a GitHub secret, so the report can\'t be read.\n';
else {
  try {
    const r = await fetch(`${SITE}/api/health.php`, { headers: { Authorization: `Bearer ${TOKEN}`, 'User-Agent': 'traversence-towns' } });
    const d = await r.json();
    if (!r.ok || d.ok === false) md += `The health report answered ${r.status}: ${s(d.error?.message || '')}\n`;
    else if (!d.towns) md += 'The health report has no towns section yet (it comes with health.php from towns-health_20261110.zip).\n';
    else {
      md += `**Jobs:** ${Object.entries(d.town_jobs || {}).map(([k, v]) => `${k} ${v}`).join(', ') || 'none'}\n\n`;
      const crawler = (d.status || []).filter((x) => /crawl|worker/i.test(x.name)).map((x) => `${x.name}: ${x.state}`).join('; ');
      if (crawler) md += `**Crawler:** ${s(crawler)}\n\n`;
      md += '| Town | Kind | Status | Tries | Found | Published | In Review | Already known | Error | Updated |\n|---|---|---|---|---|---|---|---|---|---|\n';
      for (const [, t] of Object.entries(d.towns)) for (const j of t.jobs) md += `| ${s(t.town)} | ${s(j.kind)} | ${s(j.status)} | ${j.attempts} | ${j.found} | ${j.published} | ${j.in_review} | ${j.known} | ${s(j.error)} | ${s(j.at)} |\n`;
    }
  } catch (e) { md += `Couldn't read the health report: ${s(String(e))}\n`; }
}
writeFileSync('site-audit/towns.md', md);
console.log('wrote site-audit/towns.md');
