// tools/page-audit/towns.mjs — towns built on demand (decisions/0147, 0149), from the health report: each town's crawl
// jobs (eat, stay, do, shops, care), what they found, published and left in Review, and any error. Totals only.
// Needs HEALTH_TOKEN (the GitHub secret). Writes site-audit/towns.md, and the crawler revamp's snapshot
// (site-audit/crawler-snapshot.md, with a day-by-day history in site-audit/results/crawler-snapshot.json).
// Run by .github/workflows/search-probe.yml.
import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs';
const SITE = process.env.SITE || 'https://traversence.com';
// the token: HEALTH_TOKEN, else the health_token inside CHECK_ACCOUNTS (System Configuration → Test accounts puts it there)
let TOKEN = process.env.HEALTH_TOKEN || '';
if (!TOKEN && process.env.CHECK_ACCOUNTS) { try { TOKEN = JSON.parse(process.env.CHECK_ACCOUNTS).health_token || ''; } catch (e) {} }
const s = (v) => (v == null ? '' : String(v)).replace(/\|/g, '/');
let md = `# Towns built on demand\n\nFrom the health report (\`/api/health.php\`), ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC. Generated by \`tools/page-audit/towns.mjs\`; don't edit by hand.\n\n`;
if (!TOKEN) md += 'No health token: neither HEALTH_TOKEN nor CHECK_ACCOUNTS (with its health_token) is set as a GitHub secret.\n';
else {
  try {
    const r = await fetch(`${SITE}/api/health.php`, { headers: { Authorization: `Bearer ${TOKEN}`, 'User-Agent': 'traversence-towns' } });
    const d = await r.json();
    // the server's versions (site audit P1, Jason 2026-11-08): the code check (R04) judges code against the real PHP
    if (r.ok && d.php) { mkdirSync('site-audit/results', { recursive: true }); writeFileSync('site-audit/results/server.json', JSON.stringify({ at: new Date().toISOString(), php: d.php, php_major_minor: d.php_major_minor || '', mysql: d.mysql || '' }, null, 1) + '\n'); }
    if (r.ok && d.crawler) crawlerSnapshot(d.crawler);   // the crawler revamp's numbers (handoffs/crawler-revamp.md Phase 0)
    if (!r.ok || d.ok === false) md += `The health report answered ${r.status}: ${s(d.error?.message || '')}\n`;
    else if (!d.towns) md += 'The health report has no towns section yet (it comes with health.php from towns-health_20261110.zip).\n';
    else {
      md += `**Jobs:** ${Object.entries(d.town_jobs || {}).map(([k, v]) => `${k} ${v}`).join(', ') || 'none'}\n\n`;
      const runs = (d.jobs || []).filter((j) => /guide_ondemand|landmark|listings_tick|guide_finds/.test(j.job));   // scheduled jobs that fill towns: when each last ran
      if (runs.length) md += `**Scheduled jobs (last run, site time):** ${runs.map((j) => `${j.job} ${s(j.last) || 'never'}${j.ok === 0 || j.ok === false ? ' (failed)' : ''}${j.fails_today ? `, ${j.fails_today} failed today` : ''}`).join('; ')}\n\n`;
      if (d.landmark_kinds_unfiled && d.landmark_kinds_unfiled.length) md += `**Landmark kinds with no category yet** (give a category this word as a term): ${d.landmark_kinds_unfiled.map((k) => `${s(k.fclass)} ${k.n}`).join('; ')}\n\n`;
      if (d.osm_asks_hour != null) md += `**OpenStreetMap asks:** ${d.osm_asks_hour} this hour; last: ${(d.osm_asks_last || []).map((a) => `${s(a.qkey)} found ${a.found} (${s(a.asked_at)})`).join('; ') || 'none'}\n\n`;
      if (d.index_mark) md += `**Search has caught up with listing changes to:** ${s(d.index_mark)} (site time)\n\n`;
      const crawler = (d.status || []).filter((x) => /crawl|worker/i.test(x.name)).map((x) => `${x.name}: ${x.state}`).join('; ');
      if (crawler) md += `**Crawler:** ${s(crawler)}\n\n`;
      md += '| Town | Kind | Status | Tries | Found | Published | In Review | Already known | Error | Updated |\n|---|---|---|---|---|---|---|---|---|---|\n';
      for (const [, t] of Object.entries(d.towns)) for (const j of t.jobs) md += `| ${s(t.town)} | ${s(j.kind)} | ${s(j.status)} | ${j.attempts} | ${j.found} | ${j.published} | ${j.in_review} | ${j.known} | ${s(j.error)} | ${s(j.at)} |\n`;
      const kv = (o) => (o && typeof o === 'object' ? Object.entries(o).map(([k, v]) => `${k} ${v}`).join(', ') : '') || 'none';
      md += '\n## Where each town\'s places are\n\n| Town | Listings | Searchable | Landmarks |\n|---|---|---|---|\n';
      for (const [, t] of Object.entries(d.towns)) md += `| ${s(t.town)} | ${s(kv(t.listings))} | ${s(kv(t.searchable))} | ${s(kv(t.landmarks))} |\n`;
      md += '\n## Places looked up by name\n\n';
      for (const name of ['Four Corners', 'Laguna Art', 'Dana Point Harbor']) {
        try {
          const f = (await (await fetch(`${SITE}/api/health.php?find=${encodeURIComponent(name)}`, { headers: { Authorization: `Bearer ${TOKEN}`, 'User-Agent': 'traversence-towns' } })).json()).find || {};
          md += `**${name}**\n- Landmarks: ${(f.landmarks || []).map((x) => `${s(x.name)} (${s(x.status)}${x.nation ? ', ' + s(x.nation) + ' land' : ''}${x.why ? ': ' + s(x.why) : ''}, #${x.gnis_id})`).join('; ') || 'none'}\n`;
          md += `- Searchable: ${(f.searchable || []).map((x) => `${s(x.label)} (${s(x.kind)})`).join('; ') || 'none'}\n- Listings: ${(f.listings || []).map((x) => `${s(x.name)}, ${s(x.city)} ${s(x.state)}${+x.is_suppressed ? ' (hidden)' : ''}`).join('; ') || 'none'}\n\n`;
        } catch (e) { md += `**${name}**: couldn't look it up (${s(String(e))})\n\n`; }
      }
    }
  } catch (e) { md += `Couldn't read the health report: ${s(String(e))}\n`; }
}
writeFileSync('site-audit/towns.md', md);
console.log('wrote site-audit/towns.md');

// The crawler revamp's snapshot: each store's counts today, and the change since the first day recorded.
function crawlerSnapshot(c) {
  const day = new Date().toISOString().slice(0, 10);
  const file = 'site-audit/results/crawler-snapshot.json';
  let hist = {};
  try { if (existsSync(file)) hist = JSON.parse(readFileSync(file, 'utf8')) || {}; } catch (e) { hist = {}; }
  hist[day] = c;
  const days = Object.keys(hist).sort().slice(-90);
  hist = Object.fromEntries(days.map((k) => [k, hist[k]]));
  mkdirSync('site-audit/results', { recursive: true });
  writeFileSync(file, JSON.stringify(hist, null, 1) + '\n');
  const first = hist[days[0]];
  const flat = (o, pre = '') => Object.entries(o || {}).flatMap(([k, v]) => (v && typeof v === 'object' && !Array.isArray(v) ? flat(v, pre + k + ' · ') : [[pre + k, v]]));
  const was = Object.fromEntries(flat(first));
  const label = {
    finds: 'Staged finds, by state', staged: 'Of the staged (newest 3,000 checked)', place_store: 'The place store', websites_taken_off: 'Websites taken off listings, by month',
    refresh: 'Website checks', map_points: 'Public listings and map points', town_jobs: 'Town jobs', coverage_jobs: 'Coverage jobs', identity_jobs: 'Identity jobs',
    register: 'The source register', osm_in_listings: 'OpenStreetMap values in listings (listings, by fact)', heritage: 'Heritage facts (tier / status)', landmarks: 'Landmarks, by status', guides: 'Guides (status / last draft)',
  };
  let out = `# The crawler's stores: the revamp's snapshot\n\nFrom the health report (\`/api/health.php\`, its \`crawler\` section), ${day}. Counts only, read-only. Generated by \`tools/page-audit/towns.mjs\`; don't edit by hand. The plan: \`handoffs/crawler-revamp.md\`.\n\n`;
  out += `Change is since ${days[0]}, the first day recorded.\n\n`;
  for (const [k, v] of Object.entries(c)) {
    if (k === 'at') continue;
    out += `## ${label[k] || k}\n\n`;
    if (v && v.error) { out += `Couldn't count: ${s(v.error)}\n\n`; continue; }
    const rows = flat(v, k + ' · ');
    if (!rows.length) { out += 'None.\n\n'; continue; }
    out += '| What | Now | Change |\n|---|---|---|\n';
    for (const [path, val] of rows) {
      const before = was[path];
      const ch = typeof val === 'number' && typeof before === 'number' && days.length > 1 ? (val - before > 0 ? `+${val - before}` : `${val - before}`) : '';
      out += `| ${s(path.slice(k.length + 3))} | ${s(val)} | ${ch} |\n`;
    }
    out += '\n';
  }
  writeFileSync('site-audit/crawler-snapshot.md', out);
  console.log('wrote site-audit/crawler-snapshot.md');
}
