#!/usr/bin/env python3
"""The page tree becomes the source of truth, without losing a route (site audit P6, Jason 2026-11-08).

    python3 tools/page-audit/routes-check.py --mirror <traverse-3way-sync checkout> [--docs <this repo>]

Writes site-audit/routes-check.md:
  1. Every route `routes.md` names that isn't a page on the server (each to settle: the tree missed it, or it's gone and
     goes in archive.md). `routes.md` is archived only when this list is empty.
  2. Every page on the server in neither `routes.md` nor `archive.md`, with the evidence for each (how many other files
     link to it, whether a menu shows it) and a suggested call (live, archive, remove), for Jason to approve.
Standard library only; reads the same files as audit.py.
"""
import argparse, datetime, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import audit  # noqa: E402

MENUS = ('app/ui/section-rails.php', 'app/admin/manifests.php', 'app/ui/header.php', 'app/ui/footer.php', 'app/ui/routes.php')


def routes_named(text):
    """The page addresses routes.md names in its tables' first column: [(address, status, line)]."""
    out = []
    for i, line in enumerate(text.splitlines(), 1):
        if not line.startswith('| `') and not line.startswith('| /'):
            continue
        cells = [c.strip() for c in line.strip('|').split('|')]
        first, status = cells[0], (cells[-1] if len(cells) > 1 else '')
        for tok in re.findall(r'`([^`]+)`', first):
            for part in re.split(r'[\s,]+', tok):
                p = part.split('?')[0].strip()
                if p.startswith('/') and not p.startswith('//') and not re.search(r'\{|\*|<', p):
                    out.append((p, status, i))
        for f in re.findall(r'\(`([\w/.-]+\.php)`\)', first):
            out.append(('/' + f.lstrip('/'), status, i))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--mirror', required=True)
    ap.add_argument('--docs', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
    a = ap.parse_args()
    files = audit.load(a.mirror)
    pages = {audit.page_url(p): p for p in files if audit.is_page(p)}
    exists = set(pages) | {u + 'index.php' for u in pages if u.endswith('/')} | {p[len('website'):] for p in files if p.startswith('website/')}
    docs = a.docs
    routes = open(os.path.join(docs, 'routes.md'), encoding='utf-8').read()
    archive = open(os.path.join(docs, 'archive.md'), encoding='utf-8').read()

    # 1. routes.md's addresses that aren't on the server
    missing, seen = [], set()
    for url, status, line in routes_named(routes):
        u = url if url.endswith(('/', '.php')) else url + '/'
        if url in exists or u in exists or url.rstrip('/') + '/index.php' in exists or url in seen:
            continue
        seen.add(url)
        if re.search(r'designed|not built|remove|moved', status, re.I):
            note = 'routes.md already says: ' + status
        elif url in archive:
            note = 'in archive.md'
        else:
            note = 'to settle: a page the tree missed, or gone (then into archive.md)'
        missing.append((url, line, note))

    # 2. pages in neither list, with the evidence
    menus = ''.join(files.get(m, '') for m in MENUS)
    listed = routes + archive
    rows = []
    for url, path in sorted(pages.items()):
        inlist = url in listed or path[len('website/'):] in listed or (url.rstrip('/') and url.rstrip('/') + '/' in listed)
        if inlist:
            continue
        needle = url if url != '/' else None
        links = 0
        if needle:
            pat = re.compile(re.escape(needle.rstrip('/')) + r'(?:/|\?|\'|"|$)' if needle.endswith('/') else re.escape(needle) + r'(?![\w.-])')
            for p, src in files.items():
                if p != path and pat.search(src):
                    links += 1
        in_menu = bool(needle) and needle.rstrip('/') in menus
        src = files[path]
        redirect = bool(re.search(r"header\(\s*['\"]Location:", src)) and len(src) < 1500
        if redirect:
            call = 'archive (it only forwards)'
        elif in_menu or links >= 2:
            call = 'live'
        elif links == 1:
            call = 'live (one link: check it)'
        else:
            call = 'archive or remove (nothing links to it)'
        rows.append((url, path, links, 'yes' if in_menu else '', call))

    now = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
    L = ['# Routes against the page tree', '',
         'Site audit P6 (Jason, 2026-11-08: "the page tree becomes the source of truth, without losing a route"). Generated by',
         f'`tools/page-audit/routes-check.py` on {now} from the live mirror. Don\'t edit by hand.', '',
         f'## 1. Routes in `routes.md` that aren\'t a page on the server ({len(missing)})', '',
         '`routes.md` is archived once each of these is settled.', '']
    if missing:
        L += ['| Address | routes.md line | What to do |', '|---|---|---|'] + [f'| `{u}` | {ln} | {n} |' for u, ln, n in missing]
    else:
        L += ['None: every route in `routes.md` is a page on the server.']
    L += ['', f'## 2. Pages on the server in neither `routes.md` nor `archive.md` ({len(rows)})', '',
          'The evidence for each: how many other files link to it, and whether a menu shows it. **Suggested** is a starting',
          'point; Jason approves the list (or changes a call), then each goes into the page tree as live, or into',
          '`archive.md` as archived or to remove.', '',
          '| Address | File | Linked from | In a menu | Suggested |', '|---|---|---|---|---|']
    L += [f'| `{u}` | `{p}` | {n} file{"s" if n != 1 else ""} | {m} | {c} |' for u, p, n, m, c in rows]
    open(os.path.join(docs, 'site-audit', 'routes-check.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print(f'{len(missing)} route(s) to settle, {len(rows)} unlisted page(s)')


if __name__ == '__main__':
    main()
