#!/usr/bin/env python3
"""
Builds app/data/word-senses.php from WordNet 3.1 (decisions/0144): each noun with what its commonest meanings are, so a
catalog item's name tells which of the nine kinds it can be (ItemKinds::fit: tamales are food, so not a service; a puppy
is an animal, so not made to order).

Usage: python3 build_senses.py /path/to/wordnet31/dict /path/to/app/data/word-senses.php

Per noun: up to three of its common senses (proper nouns left out), most common first, as one letter each (WordNet's lexicographer file):
  f food   a animal   p plant   t artifact (a made thing)   c act (work, a service, an activity)   e event
  m communication (a book, a guide, a pattern, a course)   l location   r person   s substance   o natural object
  - anything else (a feeling, a quantity, an attribute…)
WordNet: Princeton University, "About WordNet", 2010 (license in word-families.LICENSE). The copy used came from the
MIT-licensed npm package wordnet-db 3.1.14. Run again to rebuild; nothing else reads WordNet.
"""
import os, sys

WN, OUT = sys.argv[1], sys.argv[2]
LEX = {4: 'c', 5: 'a', 6: 't', 10: 'm', 11: 'e', 13: 'f', 15: 'l', 17: 'o', 18: 'r', 20: 'p', 27: 's'}

# synset offset -> lexicographer file number, and the words written with a capital there (a proper noun: Tamale the
# city, Chile the country), from data.noun; a proper-noun sense never decides what an item is
lexfile = {}; proper = {}
with open(os.path.join(WN, 'data.noun'), encoding='latin-1') as f:
    for line in f:
        if line.startswith('  '):
            continue
        parts = line.split(' ')
        lexfile[parts[0]] = int(parts[1])
        n = int(parts[3], 16)
        proper[parts[0]] = {parts[4 + 2 * i].lower() for i in range(n) if parts[4 + 2 * i][:1].isupper()}

out = {}
with open(os.path.join(WN, 'index.noun'), encoding='latin-1') as f:
    for line in f:
        if line.startswith('  '):
            continue
        p = line.split()
        lemma = p[0].replace('_', ' ')
        if any(ch.isdigit() for ch in lemma) or lemma.count(' ') > 1:
            continue
        n = int(p[2]); pc = int(p[3])
        offsets = p[4 + pc + 2:4 + pc + 2 + n]
        offsets = [o for o in offsets if p[0] not in proper.get(o, set())]   # common senses only
        code = ''.join(LEX.get(lexfile.get(o, 0), '-') for o in offsets[:3])
        if code.strip('-') == '':
            continue
        out[lemma] = code

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('<?php\n// Generated by workers/lexicon/build_senses.py from WordNet 3.1 (decisions/0144). Do not edit: rebuild.\n')
    f.write('// noun => its commonest senses, one letter each: f food, a animal, p plant, t artifact, c act, e event, m communication,\n')
    f.write('// l location, r person, s substance, o natural object, - other.\nreturn [')
    f.write(','.join("'" + k.replace("\\", "\\\\").replace("'", "\\'") + "'=>'" + v + "'" for k, v in sorted(out.items())))
    f.write('];\n')
print(len(out), 'nouns')
