#!/usr/bin/env python3
"""
Builds app/data/demonyms.php from Wikidata (CC0): each country's and U.S. state's English demonyms, the word for its
people ("Mexican" for Mexico, "Italian" for Italy, "Irish" for Ireland, "Arizonan" for Arizona), so search can offer a
partly typed word as the place, its food and its culture from a source, never a hand list (Jason, 2026-11-11: "What we
hold seems to be a gate to information"). Tribal nations come from the site's own nations table, under decisions/0066.

Usage: python3 build_demonyms.py out.php   (.github/workflows/lexicon-demonyms.yml runs it and commits the file)
Output: <?php return ['peoples' => ['mexican' => ['Mexico'], ...], 'places' => ['mexico' => ['mexican'], ...]];
"""
import json, sys, urllib.parse, urllib.request

OUT = sys.argv[1]
Q = """SELECT ?label ?dem WHERE {
  { ?item wdt:P31 wd:Q6256 . } UNION { ?item wdt:P31 wd:Q3624078 . } UNION { ?item wdt:P31 wd:Q35657 . }
  ?item wdt:P1549 ?dem . FILTER(LANG(?dem) = "en")
  ?item rdfs:label ?label . FILTER(LANG(?label) = "en")
}"""
req = urllib.request.Request('https://query.wikidata.org/sparql?format=json&query=' + urllib.parse.quote(Q),
                             headers={'User-Agent': 'TraversenceLexicon/1.0 (https://traversence.com)', 'Accept': 'application/sparql-results+json'})
rows = json.load(urllib.request.urlopen(req, timeout=120))['results']['bindings']
peoples, places = {}, {}
for r in rows:
    place, dem = r['label']['value'].strip(), r['dem']['value'].strip()
    if not place or not dem or ' ' in dem.strip() and len(dem.split()) > 2:
        continue
    d = dem.lower()
    peoples.setdefault(d, [])
    if place not in peoples[d]:
        peoples[d].append(place)
    places.setdefault(place.lower(), [])
    if d not in places[place.lower()]:
        places[place.lower()].append(d)
esc = lambda s: s.replace('\\', '\\\\').replace("'", "\\'")
arr = lambda m: '[' + ','.join("'" + esc(k) + "'=>[" + ','.join("'" + esc(v) + "'" for v in vs) + ']' for k, vs in sorted(m.items())) + ']'
with open(OUT, 'w') as f:
    f.write("<?php\n// Generated by workers/lexicon/build_demonyms.py from Wikidata (CC0): countries' and U.S. states' English demonyms.\n// Do not edit: rebuild with .github/workflows/lexicon-demonyms.yml.\n")
    f.write("return ['peoples'=>" + arr(peoples) + ",'places'=>" + arr(places) + "];\n")
print(f'{len(peoples)} demonyms, {len(places)} places')
